# I7 -- edge_thickness on ASPHERIC surfaces (the WP verified spheres only)
# ---------------------------------------------------------------------------

def _sag_oracle(h, R, k, coeffs):
    """Independent even-asphere sag, written here from the standard form

        z(h) = c h^2 / (1 + sqrt(1 - (1+k) c^2 h^2)) + sum_p a_p h^p ,

    with c = 1/R (c = 0 for a flat surface).  Not a library call.
    """
    if not np.isfinite(R):
        z = 0.0
    else:
        c = 1.0 / R
        rad = 1.0 - (1.0 + k) * c * c * h * h
        z = c * h * h / (1.0 + np.sqrt(rad)) if rad >= 0.0 else float('nan')
    for p, a in (coeffs or {}).items():
        z = z + a * h ** float(p)
    return z


# (tag, R1, R2, tc, h, k1, k2, aspheric_1, aspheric_2)
_EDGE_SHAPES = [
    ('parabola + A4 + A6', 30e-3, -60e-3, 6e-3, 11e-3, -1.0, 0.0,
     {4: 3.2e3, 6: -1.1e8}, None),
    ('hyperbolae both sides, A4 + A8', 26e-3, -26e-3, 7e-3, 10e-3,
     -2.5, -3.0, {4: -5.0e2, 8: 2.0e12}, {4: 8.0e2, 6: 4.0e7}),
    ('oblate k>0 + A4 + A10', 40e-3, -18e-3, 4e-3, 9e-3, 2.0, 0.5,
     {4: 1.0e4}, {4: -2.0e4, 10: 7.0e16}),
    ('aspheric plano-rear', 50e-3, float('inf'), 3e-3, 12e-3, -0.7, 0.0,
     {4: 2.0e3, 6: 5.0e7}, None),
    ('knife edge, negative result', 12e-3, -12e-3, 1.0e-3, 10e-3,
     0.0, 0.0, None, None),
]


@pytest.mark.parametrize('tag,R1,R2,tc,h,k1,k2,a1,a2', _EDGE_SHAPES,
                         ids=[s[0] for s in _EDGE_SHAPES])
def test_verify_i7_edge_thickness_matches_an_independent_aspheric_sag(
        tag, R1, R2, tc, h, k1, k2, a1, a2):
    """``t_edge = tc + sag(R2,k2,h) - sag(R1,k1,h)`` against the closed form
    above, on conics and aspheres the WP's four spherical shapes did not
    reach (parabola, two hyperbolae, an oblate k > 0, a plano rear, and a
    genuine knife edge whose answer is negative).

    Bar derivation: both sides evaluate the same exact expression in float64
    on O(1e-3) m quantities, so the floor is a handful of ULPs of the largest
    intermediate -- ~1e-19 m.  Measured worst |delta| over these five shapes
    plus the WP's four on 2026-09-12: 8.7e-19 m.  The bar 1e-15 m therefore
    sits ~3 decades above the float64 floor and ~12 decades below the
    smallest edge-thickness error that could matter optically (1 um).
    """
    rx = la.make_singlet(R1, R2, tc, 'N-BK7', aperture=2 * h)
    rx['surfaces'][0]['conic'] = k1
    rx['surfaces'][1]['conic'] = k2
    rx['surfaces'][0]['aspheric_coeffs'] = a1
    rx['surfaces'][1]['aspheric_coeffs'] = a2
    got = edge_thickness(rx, 0)
    expected = tc + _sag_oracle(h, R2, k2, a2) - _sag_oracle(h, R1, k1, a1)
    assert np.isfinite(expected), 'fixture must be well defined at h'
    assert abs(got - expected) < 1e-15, (
        f'{tag}: edge_thickness {got!r} vs independent sag {expected!r}')


def test_verify_i7_undefined_edge_is_a_maximal_violation():
    """A surface that does not reach the clear semi-diameter (R = 8 mm at
    h = 10 mm) has no sag, so ``edge_thickness`` is ``nan`` -- and the merit
    must score that slot as a MAXIMAL violation, not skip it (V3).

    Pre-fix (`658e6142` .. VERIFY-A10 §2) the NaN slot was ``continue``-d, so
    the contribution was **0.0**: an element whose surfaces do not even reach
    their own rim scored as *satisfying* a manufacturability constraint,
    precisely where the constraint bites.  That is the reward-the-failure
    shape S4-5 fixed for a NaN ``strehl_best`` in ``driver.py``.

    Bar derivation: with the slot unmeasurable the deficit is the whole
    budget, so the contribution is exactly ``weight * min_edge**2`` --
    ``1.0 * (1e-3)**2 = 1e-6`` -- an exact product of two
    double-representable numbers, hence the ``rel=1e-15`` (one rounding).
    Two-sided: a WELL-DEFINED knife edge is still penalised by its own
    (smaller) deficit, and a healthy element still scores 0.
    """
    from lumenairy.optimize import MinEdgeThicknessMerit
    rx = la.make_singlet(8e-3, -8e-3, 2e-3, 'N-BK7', aperture=20e-3)
    assert np.isnan(edge_thickness(rx, 0)), (
        'fixture must actually produce an unmeasurable edge')

    class _Ctx:
        prescription = rx
    merit = MinEdgeThicknessMerit(min_edge=1e-3)
    assert merit.evaluate(_Ctx()) == pytest.approx(1e-6, rel=1e-15), (
        'an unmeasurable edge must cost the full min_edge**2, not 0.0')

    # A well-defined knife edge: t_edge = -9.7335e-3 m, so the deficit is
    # 1e-3 - (-9.7335e-3) = 1.07335e-2 and the contribution 1.152e-4 -- larger
    # than the NaN case, i.e. the ordering "measurably worse > unmeasurable"
    # is preserved and the NaN arm is not swamping real geometry.
    rx2 = la.make_singlet(12e-3, -12e-3, 1e-3, 'N-BK7', aperture=20e-3)

    class _Ctx2:
        prescription = rx2
    knife = MinEdgeThicknessMerit(min_edge=1e-3).evaluate(_Ctx2())
    assert knife > 1e-6

    # ... and a healthy element still scores exactly zero.
    rx3 = la.make_singlet(60e-3, -60e-3, 6e-3, 'N-BK7', aperture=10e-3)

    class _Ctx3:
        prescription = rx3
    assert np.isfinite(edge_thickness(rx3, 0))
    assert MinEdgeThicknessMerit(min_edge=1e-3).evaluate(_Ctx3()) == 0.0


