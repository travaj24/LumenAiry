def test_verify_v10_no_unicode_line_separator_reaches_a_generated_script(
        tmp_path):
    """No character that ``str.splitlines()`` treats as a line boundary may
    survive into an emitted script.

    U+0085 / U+2028 / U+2029 sit outside the C0 range the comment sanitiser
    stripped.  ``_comment_text`` happened to catch them anyway (its trailing
    whitespace collapse matches Unicode whitespace), but the per-lens
    ``# {comment}`` line in the unrolled emitter did not call it at all --
    measured on ``658e6142``: exactly one line of the generated script
    carried a RAW U+2028, and it was that one.

    CPython does not treat these as SOURCE newlines (measured at the end), so
    this was never exploitable; the defect is that a tool re-reading the
    script line by line disagrees with the compiler about where the comment
    ends.  Two-sided: the payload text still appears, joined onto one line, so
    the comment is not simply being dropped.

    (The separators are built with ``chr()`` on purpose -- a literal U+2028 in
    a source file is invisible and editor-fragile.)
    """
    import ast

    from lumenairy.io.codegen import _comment_text, generate_simulation_script
    LS, PS, NEL = chr(0x2028), chr(0x2029), chr(0x85)
    # The leaking site is the per-lens ``# {comment}`` line, whose text
    # is the FIRST surface's COMM -- so the payload has to go there.
    MARKS = 'MARKA' + LS + 'MARKB' + PS + 'MARKC' + NEL + 'MARKD'

    # the unit half
    probe = 'a' + LS + 'b' + PS + 'c' + NEL + 'd\ne\tf'
    out = _comment_text(probe)
    assert len(out.splitlines()) == 1, ascii(out)
    assert out == 'a b c d e f'

    # the end-to-end half: the site that actually leaked
    zmx = (
        'VERS 210000 0 123 0 0\nMODE SEQ\nUNIT MM X W X CM MR CPMM\n'
        'SURF 0\n  TYPE STANDARD\n  CURV 0\n  DISZ INFINITY\n'
        'SURF 1\n  TYPE STANDARD\n  STOP\n  CURV 0.02\n  DISZ 5.0\n'
        '  GLAS N-BK7 0 0 1.5 50 0 0 0 0 0 0\n'
        '  COMM ' + MARKS + '\n  DIAM 12.7\n'
        'SURF 2\n  TYPE STANDARD\n  CURV 0\n  DISZ 50.0\n  DIAM 12.7\n'
        'SURF 3\n  TYPE STANDARD\n  CURV 0\n  DISZ 0\n  DIAM 12.7\n')
    f = tmp_path / 'sep.zmx'
    f.write_text(zmx, encoding='utf-8')
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        rx = la.load_zemax_zmx(str(f))
        rx['name'] = MARKS
        src = generate_simulation_script(rx, wavelength=1.31e-6, N=32,
                                         include_plotting=False,
                                         include_analysis=False)
    for ch, nm in ((LS, 'U+2028'), (PS, 'U+2029'), (NEL, 'U+0085')):
        hits = [i for i, ln in enumerate(src.split('\n'), 1) if ch in ln]
        assert not hits, f'{nm} survived into the generated script, line {hits}'
    assert 'MARKA MARKB MARKC MARKD' in src   # still present, one line
    ast.parse(src)                            # and still compiles

    # why this was inert, measured rather than assumed: U+2028 is NOT a
    # source-line terminator for CPython's tokenizer.
    ns = {}
    exec(compile("q = 'a" + LS + "b'\n", '<probe>', 'exec'), ns)
    assert ns['q'] == 'a' + LS + 'b'


