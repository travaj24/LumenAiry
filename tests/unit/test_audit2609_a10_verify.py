# The same physical singlet -- R1 = 50 mm, R2 = -50 mm, tc = 4 mm, half
# aperture 12.7 mm, BFL 90 mm -- written in each of the pre-fix writer's
# three unit spellings.
_LEGACY_FILES = {
    'M': dict(dim='M', ape='0.012700', r1='0.05000000', r2='-0.05000000',
              t1='0.00400000', bfl='0.09000000'),
    'MM': dict(dim='MM', ape='12.700000', r1='50.00000000', r2='-50.00000000',
               t1='4.00000000', bfl='90.00000000'),
    'IN': dict(dim='IN', ape='0.500000', r1='1.96850394', r2='-1.96850394',
               t1='0.15748031', bfl='3.54330709'),
}


def _write_legacy(tmp_path, spelling):
    p = tmp_path / f'legacy_{spelling}.seq'
    p.write_text(_LEGACY_HEAD.format(**_LEGACY_FILES[spelling]))
    return str(p)


@pytest.mark.parametrize('spelling', ['MM', 'IN'])
def test_verify_i1_pre_v546_mm_and_in_files_keep_their_own_units(
        tmp_path, spelling):
    """A pre-v5.46 file written with ``units='MM'`` / ``'IN'`` must read the
    same as it always did.

    WP-A10's legacy sniff (banner present + format marker absent) applied a
    blanket SI-metre scale regardless of the file's ``DIM`` token, so these
    two spellings -- which the pre-fix docstring advertised as "useful for
    handing files to CODE V users" -- were mis-read.  Measured on the code as
    committed in ``658e6142``, on exactly the fixtures below:

        DIM MM : R1 = 50.0 m       (pre-v5.46 loader: 0.05 m)  -> x1000
        DIM IN : R1 = 1.96850394 m (pre-v5.46 loader: 0.05 m)  -> x39.37

    Bar: the file numbers are exact decimal strings and the unit factors are
    exact (1 mm = 1e-3 m; 1 in = 0.0254 m, NIST SP 811), so the only error is
    the writer's own ``%.8f`` quantisation -- 1e-8 in the file's unit, i.e.
    2e-10 relative on a 50 mm radius for ``MM`` and 5e-9 for ``IN``.  The bar
    below (rel=1e-7) sits ~1.5 decades above that floor and 6 decades below
    the smallest defect it must catch (a factor of 39).
    """
    p = _write_legacy(tmp_path, spelling)
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter('always')
        rx = la.load_codev_seq(p)
    assert rx['surfaces'][0]['radius'] == pytest.approx(50e-3, rel=1e-7), (
        f"a pre-v5.46 'DIM {spelling}' file carries "
        f"{'millimetres' if spelling == 'MM' else 'inches'}, not metres")
    assert rx['surfaces'][1]['radius'] == pytest.approx(-50e-3, rel=1e-7)
    assert rx['thicknesses'][0] == pytest.approx(4e-3, rel=1e-7)
    assert rx['aperture_diameter'] == pytest.approx(25.4e-3, rel=1e-7)
    # ... and nothing is ambiguous about such a file, so it must not warn
    # about the migration at all.
    assert not [w for w in caught if 'before v5.46' in str(w.message)], (
        "a 'DIM MM' / 'DIM IN' legacy file reads identically under both "
        "conventions -- there is nothing to warn about")


