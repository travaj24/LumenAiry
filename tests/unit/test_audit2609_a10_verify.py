def test_verify_i3_inch_file_with_a_fold_mirror_round_trips(tmp_path):
    """A fixture the work package did not use: inches (``DIM I``), a
    parabola carrying ``A``/``B``/``J`` (y^4, y^6, y^20), and a fold mirror
    in AIR between two glass elements.

    Oracles, all computed here: the inch definition (0.0254 m exactly), the
    lens-unit rescale ``a_p = a_file / L**(p-1)``, and the requirement that
    the mirror's two legs (1.5 in + 2.0 in) fold into ONE refractive gap.

    Bars: the coefficient and radius identities are exact products of
    double-representable numbers, so ``rel=1e-15`` is one rounding above the
    floor; the round-trip bar is ``rel=1e-9``, one decade above the writer's
    ``%.10E`` / ``%.8f`` quantisation (2e-10 relative on a 50 mm radius).
    """
    p = tmp_path / 'inch_fold.seq'
    p.write_text(_INCH_SEQ)
    L = 0.0254
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter('always')
        rx = la.load_codev_seq(str(p))
    assert not caught, [str(w.message)[:70] for w in caught]

    assert rx['surfaces'][0]['radius'] == pytest.approx(2.0 * L, rel=1e-15)
    assert rx['surfaces'][0]['conic'] == -1.0
    asph = rx['surfaces'][0]['aspheric_coeffs']
    for power, a_file in ((4, 1.0e-4), (6, -2.5e-6), (20, 7.0e-15)):
        assert asph[power] == pytest.approx(a_file / L ** (power - 1),
                                            rel=1e-15), f'A_{power}'

    types_ = [e['element_type'] for e in rx['elements']]
    assert types_ == ['surface', 'surface', 'mirror', 'surface', 'surface']
    assert la.has_mirrors(rx)
    # The mirror's legs (1.5 + 2.0 inches) collapse into one refractive gap.
    assert rx['all_thicknesses'] == pytest.approx(
        [0.25 * L, 1.5 * L, 2.0 * L, 0.2 * L], rel=1e-15)
    assert rx['thicknesses'] == pytest.approx(
        [0.25 * L, 3.5 * L, 0.2 * L], rel=1e-15)

    q = tmp_path / 'inch_fold_rt.seq'
    with warnings.catch_warnings(record=True) as w2:
        warnings.simplefilter('always')
        la.export_codev_seq(rx, str(q), wavelength=632.8e-9, units='I',
                            back_focal_length=rx.get('back_focal_length', 0.0))
        back = la.load_codev_seq(str(q))
    assert not w2, [str(x.message)[:70] for x in w2]
    assert [e['element_type'] for e in back['elements']] == types_
    for a, b in zip(rx['elements'], back['elements']):
        if np.isfinite(a['radius']):
            assert b['radius'] == pytest.approx(a['radius'], rel=1e-9)
        else:
            assert not np.isfinite(b['radius'])
        assert b['conic'] == pytest.approx(a['conic'], abs=1e-9)
        if a['aspheric_coeffs']:
            for k, v in a['aspheric_coeffs'].items():
                assert b['aspheric_coeffs'][k] == pytest.approx(v, rel=1e-9)
    assert back['thicknesses'] == pytest.approx(rx['thicknesses'], rel=1e-9)


def test_verify_i5_hostile_glass_token_never_reaches_a_code_position(
        tmp_path):
    """Payloads of the verifier's own construction (quote-escape, both
    quote styles, a backslash, a U+2028 line separator, a ``\"\"\"``
    terminator) must appear only inside string constants of the generated
    script -- never as a Call node.

    Oracle: Python's own ``ast``.  A ``Call`` whose callee is named
    ``system`` / ``__import__`` / ``eval`` / ``exec`` is live code; pre-fix
    the audit's payload produced exactly that (the emitted GLASS_REGISTRY
    line parsed as TWO statements).
    """
    import ast

    from lumenairy.io.codegen import generate_simulation_script

    payloads = [
        "X'];__import__('os').system('echo MARK');_z=['y",
        'X"];__import__("os").system("echo MARK");_z=["y',
        "X\\\\'];__import__('os').system('echo MARK');_z=['y",
        "X\u2028__import__('os').system('echo MARK')\u2028_z='y",
        'X"""+__import__("os").system("echo MARK")+"""y',
    ]
    zmx_tmpl = (
        'VERS 210000 0 123 0 0\nMODE SEQ\nUNIT MM X W X CM MR CPMM\n'
        'SURF 0\n  TYPE STANDARD\n  CURV 0\n  DISZ INFINITY\n'
        'SURF 1\n  TYPE STANDARD\n  STOP\n  CURV 0.02\n  DISZ 5.0\n'
        '  GLAS {glas} 0 0 1.5 50 0 0 0 0 0 0\n  COMM {comm}\n  DIAM 12.7\n'
        'SURF 2\n  TYPE STANDARD\n  CURV 0\n  DISZ 50.0\n  DIAM 12.7\n'
        'SURF 3\n  TYPE STANDARD\n  CURV 0\n  DISZ 0\n  DIAM 12.7\n')
    for i, payload in enumerate(payloads):
        one = payload.replace('\n', ' ')
        tok = one.split()[0] if one.split() else 'X'
        f = tmp_path / f'evil_{i}.zmx'
        f.write_text(zmx_tmpl.format(glas=tok, comm=one), encoding='utf-8')
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            rx = la.load_zemax_zmx(str(f))
            rx['name'] = payload            # the third attack surface
            src = generate_simulation_script(
                rx, wavelength=1.31e-6, N=32,
                include_plotting=False, include_analysis=False)
        tree = ast.parse(src)               # must still be valid Python
        live = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                fn = node.func
                nm = (fn.id if isinstance(fn, ast.Name)
                      else getattr(fn, 'attr', ''))
                if nm in ('system', 'popen', 'eval', 'exec', '__import__'):
                    live.append((nm, node.lineno))
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                names = [a.name.split('.')[0] for a in node.names]
                assert not ({'os', 'subprocess', 'socket'} & set(names)), (
                    f'payload {i} injected an import: {names}')
        assert not live, f'payload {i} reached a code position: {live}'


