def test_verify_zarr_append_plane_compression_warns_instead_of_raising(
        tmp_path):
    """``append_plane(<.zarr>, compression=...)`` warns that the request is
    dropped -- it must not raise.

    WP-A10 added that warning to ``io/storage.py`` but the module has no
    ``import warnings`` (it was the only ``warnings`` reference in all 2145
    lines), so the call raised ``NameError: name 'warnings' is not defined``
    on the code as committed in ``658e6142``.  That is strictly worse than
    the silent drop the note set out to fix: a call that used to write the
    plane now writes nothing.

    Two-sided: the same call without a compression kwarg stays silent, and
    the plane is readable back in both cases.
    """
    zarr = pytest.importorskip  # noqa: F841  (documented below)
    try:
        import zarr  # noqa: F401
    except ImportError:                                  # pragma: no cover
        # TESTING_STANDARDS rule 4 forbids skipping on a RESOURCE check; a
        # missing optional BACKEND is a different thing -- there is no zarr
        # path to test at all.  Assert the import-independent half instead.
        import lumenairy.io.storage as _s
        assert 'warnings' in vars(_s) or hasattr(_s, 'warnings'), (
            'storage.py must import warnings for the zarr compression '
            'diagnostic')
        return
    from lumenairy.io import storage as S

    E = (np.arange(64, dtype=np.float64).reshape(8, 8)
         + 1j * np.arange(64, dtype=np.float64).reshape(8, 8))
    prev = S._BACKEND
    try:
        S.set_storage_backend('zarr')
        p1 = str(tmp_path / 'with_comp.zarr')
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter('always')
            S.append_plane(p1, E, dx=1e-6, label='L0',
                           compression='gzip', compression_opts=4)
        hits = [w for w in caught if 'ignores' in str(w.message)]
        assert hits, (
            f"the dropped-compression request must be diagnosed; caught "
            f"{[str(w.message)[:60] for w in caught]}")
        planes, _ = S.load_planes(p1)
        assert len(planes) == 1
        assert np.array_equal(planes[0]['field'], E.astype(planes[0]['field'].dtype))

        p2 = str(tmp_path / 'no_comp.zarr')
        with warnings.catch_warnings(record=True) as caught2:
            warnings.simplefilter('always')
            S.append_plane(p2, E, dx=1e-6, label='L0')
        assert not [w for w in caught2 if 'ignores' in str(w.message)]
    finally:
        S.set_storage_backend(prev)


