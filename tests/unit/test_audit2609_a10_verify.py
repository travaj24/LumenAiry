def test_verify_i7_focus_scan_runs_for_a_merit_class_without_the_flag(
        monkeypatch):
    """A user merit written before ``needs_focus_scan`` existed declares only
    ``needs_wave`` and may read ``ctx.strehl_best`` / ``ctx.z_best``.  The
    gate's ``getattr(m, 'needs_focus_scan', True)`` default must keep the
    scan for it, and the values it reads must be the real ones.

    Counted, not timed (TESTING_STANDARDS S1).  Measured 2026-09-12 on the
    fixture below: 5 scan calls / 155 slices with the legacy merit, and the
    merit saw a non-zero ``strehl_best`` on all 5 evaluations; the same run
    with ``RMSWavefrontMerit`` alone in the wave slot gives 0 / 0.
    """
    import lumenairy.optimize.core as _opt_core
    from lumenairy.optimize.core import MeritTerm

    class _LegacyWaveMerit(MeritTerm):
        needs_wave = True
        name = 'LegacyWave'

        def __init__(self):
            self.seen = []

        def evaluate(self, ctx):
            self.seen.append((ctx.z_best, ctx.strehl_best))
            return (1.0 - ctx.strehl_best) ** 2

    counters = {'calls': 0, 'slices': 0}
    orig = _opt_core.through_focus_scan

    def counting_scan(E, dx, wl, zs, **kw):
        counters['calls'] += 1
        counters['slices'] += len(zs)
        return orig(E, dx, wl, zs, **kw)
    monkeypatch.setattr(_opt_core, 'through_focus_scan', counting_scan)

    template = la.make_singlet(50e-3, -50e-3, 4e-3, 'N-BK7', aperture=6e-3)
    param = la.DesignParameterization(
        template=template, free_vars=[('surfaces', 0, 'radius')],
        bounds=[(30e-3, 80e-3)])
    legacy = _LegacyWaveMerit()
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        la.design_optimize(param,
                           [la.FocalLengthMerit(target=100e-3), legacy],
                           wavelength=587.6e-9, N=64, dx=20e-6,
                           method='L-BFGS-B', max_iter=1, verbose=False)
    assert counters['calls'] >= 1, (
        'the gate must default to running the scan for a merit class that '
        'does not declare needs_focus_scan')
    assert counters['slices'] == 31 * counters['calls']
    assert legacy.seen and all(s != 0.0 for _z, s in legacy.seen), (
        f'the legacy merit must see real focus results, got {legacy.seen}')

    # Control: swap the legacy merit for a library merit that declares it
    # does NOT read the scan, and the scan disappears.
    counters['calls'] = counters['slices'] = 0
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        la.design_optimize(param,
                           [la.FocalLengthMerit(target=100e-3),
                            la.RMSWavefrontMerit(max_rms_waves=0.07)],
                           wavelength=587.6e-9, N=64, dx=20e-6,
                           method='L-BFGS-B', max_iter=1, verbose=False)
    assert counters['calls'] == 0 and counters['slices'] == 0


