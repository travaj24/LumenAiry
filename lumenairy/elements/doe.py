import importlib.util as _importlib_util

_ASTROPY_AVAILABLE = _importlib_util.find_spec('astropy') is not None
_fits = None  # populated lazily by _ensure_astropy_loaded()


def _ensure_astropy_loaded():
    global _fits
    if _fits is None and _ASTROPY_AVAILABLE:
        from astropy.io import fits as _f
        _fits = _f
    return _fits is not None


def load_fits_field(
    filepath: str,
    hdu_amplitude: int = 0,
    hdu_phase: Optional[int] = None,
) -> Tuple[np.ndarray, Dict[str, Any]]:
    """
    Load a complex optical field from a FITS file.

    Supports two common formats:
    - Two HDUs: amplitude in one HDU, phase in another
    - Single HDU with complex data or [real, imag] stack along first axis

    Parameters
    ----------
    filepath : str
        Path to the .fits file.
    hdu_amplitude : int, default 0
        HDU index for the amplitude array (or complex array if hdu_phase is None).
    hdu_phase : int or None, default None
        HDU index for the phase array [radians]. If None, ``hdu_amplitude``
        is assumed to contain either complex data or a [real, imag] stack.

    Returns
    -------
    E : ndarray (complex, N×N)
        Complex field.
    metadata : dict
        Selected header keywords (wavelength, dx, dy) if present.

    Notes
    -----
    Requires the ``astropy`` package. Install via ``pip install astropy``.
    """
    if not _ASTROPY_AVAILABLE:
        raise ImportError("astropy is required for FITS support. "
                          "Install with: pip install astropy")
    _ensure_astropy_loaded()

    with _fits.open(filepath) as hdul:
        amp_data = np.array(hdul[hdu_amplitude].data)
        header = dict(hdul[hdu_amplitude].header)

        if hdu_phase is not None:
            phase_data = np.array(hdul[hdu_phase].data)
            E = amp_data * np.exp(1j * phase_data)
        elif amp_data.ndim == 3 and amp_data.shape[0] == 2:
            E = amp_data[0] + 1j * amp_data[1]
        elif np.iscomplexobj(amp_data):
            E = amp_data.astype(complex)
        else:
            # DOE-1 (AUDIT_DOE_GRATING_FREEFORM): auto-detect the SPLIT
            # amp/phase layout -- which is the DEFAULT of
            # ``save_fits_field`` (2-D real amplitude primary + a second HDU
            # tagged ``EXTNAME='PHASE'`` / ``BUNIT='radians'``).  Pre-fix the
            # default save -> default load (``hdu_phase=None``) round-trip
            # took this "amplitude only" branch and SILENTLY dropped all
            # phase (mirroring the real/imag-stack auto-detection above).
            _phase_hdu = None
            for _h in hdul[1:]:
                _hdr = _h.header
                if (str(_hdr.get('EXTNAME', '')).upper() == 'PHASE'
                        or str(_hdr.get('BUNIT', '')).lower() == 'radians'):
                    _phase_hdu = _h
                    break
            if _phase_hdu is not None and _phase_hdu.data is not None:
                phase_data = np.array(_phase_hdu.data)
                E = amp_data * np.exp(1j * phase_data)
            else:
                # Genuinely amplitude-only -- assume zero phase.
                E = amp_data.astype(complex)

    # DOE-nit (AUDIT_DOE_GRATING_FREEFORM): fall back to PIXSCALE only when
    # the specific key is ABSENT -- an explicit ``DX == 0.0`` (odd but
    # possible) should be taken literally, not treated as falsy and
    # overridden by PIXSCALE.
    _dx = header.get('DX')
    _dx = header.get('PIXSCALE') if _dx is None else _dx
    _dy = header.get('DY')
    _dy = header.get('PIXSCALE') if _dy is None else _dy
    metadata = {
        'wavelength': header.get('WAVELENG'),
        'dx': _dx,
        'dy': _dy,
    }
    return E, metadata


def save_fits_field(
    filepath: str,
    E: np.ndarray,
    wavelength: Optional[float] = None,
    dx: Optional[float] = None,
    dy: Optional[float] = None,
    metadata: Optional[Dict[str, Any]] = None,
    split_amp_phase: bool = True,
) -> None:
    """
    Save a complex optical field to a FITS file.

    Parameters
    ----------
    filepath : str
        Output .fits path.
    E : ndarray (complex, N×N)
        Complex field to save.
    wavelength : float, optional
        Wavelength [m]. Stored as WAVELENG header keyword.
    dx, dy : float, optional
        Grid spacings [m]. Stored as DX, DY header keywords.
    metadata : dict, optional
        Additional header keywords to include.
    split_amp_phase : bool, default True
        If True, save as two HDUs (amplitude + phase).
        If False, save as a single 3D array [real, imag, ...].

    Notes
    -----
    Requires ``astropy``. The split format (default) is more widely
    compatible with standard astronomy tools.
    """
    if not _ASTROPY_AVAILABLE:
        raise ImportError("astropy is required for FITS support. "
                          "Install with: pip install astropy")
    _ensure_astropy_loaded()

    header = _fits.Header()
    if wavelength is not None:
        header['WAVELENG'] = (wavelength, 'Wavelength [m]')
    if dx is not None:
        header['DX'] = (dx, 'Grid spacing in x [m]')
    if dy is not None:
        header['DY'] = (dy, 'Grid spacing in y [m]')
    if metadata:
        # DOE-nit (AUDIT_DOE_GRATING_FREEFORM): FITS keywords are capped at 8
        # chars, so two metadata keys sharing an 8-char prefix would silently
        # collapse into one card (the later value overwrites the earlier).
        # Warn on collision rather than lose data silently.
        _seen_cards: Dict[str, str] = {}
        for key, value in metadata.items():
            card = key.upper()[:8]
            if card in _seen_cards and _seen_cards[card] != key:
                warnings.warn(
                    f"save_fits_field: metadata keys {_seen_cards[card]!r} "
                    f"and {key!r} both truncate to the 8-char FITS card "
                    f"{card!r}; the later value overwrites the earlier.  "
                    f"Rename one to keep both.",
                    UserWarning, stacklevel=2)
            _seen_cards[card] = key
            header[card] = value

    if split_amp_phase:
        amp = np.abs(E).astype(np.float32)
        phase = np.angle(E).astype(np.float32)

        primary = _fits.PrimaryHDU(amp, header=header)
        primary.header['EXTNAME'] = 'AMPLITUDE'

        phase_hdu = _fits.ImageHDU(phase)
        phase_hdu.header['EXTNAME'] = 'PHASE'
        phase_hdu.header['BUNIT'] = 'radians'

        _fits.HDUList([primary, phase_hdu]).writeto(filepath, overwrite=True)
    else:
        stacked = np.stack([np.real(E), np.imag(E)]).astype(np.float32)
        primary = _fits.PrimaryHDU(stacked, header=header)
        primary.header['FORMAT'] = 'real_imag_stack'
        primary.writeto(filepath, overwrite=True)
