def makedammann2d(
    periodx: float = 61e-6,
    periody: float = 61e-6,
    waveln: float = 1.31e-6,
    wavsamp: float = 0.5,
    phaselevels: int = 8,
    phasesteps: int = 4,
    diforders: Optional[np.ndarray] = None,
    diffractionthr: float = 0.25,
    nfmov: float = 0.5,
    itr: int = 3000,
    plot: bool = True,
    plot_every: int = 50,
    seed: Optional[int] = None,
    save_path: Optional[str] = None,
    cell_pixels: Optional[Union[int, Tuple[int, int]]] = None,
    _legacy_units: str = 'SI',
) -> Tuple[np.ndarray, np.ndarray, Tuple[float, float]]:
    """
    Design a 2D Dammann grating using an iterative Fourier transform algorithm.

    Uses an IFTA (Iterative Fourier Transform Algorithm) to find a phase-only
    near-field distribution whose Fourier transform produces a uniform array
    of diffraction orders.  Phase quantisation is progressively tightened over
    the iterations (simulated-annealing style).

    .. versionchanged:: 4.14.2
        Units are now SI metres throughout (was micrometres).  ``periodx``,
        ``periody`` and ``waveln`` are expected in **metres**; the returned
        ``cell_pixel_size`` is in metres and matches them directly (no
        internal ``* 1e-6`` rescale).  Pre-4.14.2 callers passing
        ``periodx=61.0`` / ``waveln=1.31`` (micrometres) hit a thousand-
        fold drift in ``samplingx`` that was silently masked by an
        output ``* 1e-6`` rescale.  v4.14.2 emits a ``DeprecationWarning``
        when ``periodx``, ``periody`` or ``waveln`` look like micrometres
        (heuristic: ``periodx > 1e-3 m`` or ``waveln > 1e-3 m``, i.e.
        larger than 1 mm) and treats the inputs as legacy micrometre
        values; remove the warning by converting your call sites to SI
        (multiply old values by ``1e-6``).

    .. versionchanged:: 4.14.3
        The ``> 1e-3`` legacy-um heuristic silently miscompiled THz / MMW
        designs where SI-correct ``periodx`` / ``waveln`` legitimately
        exceed 1 mm (e.g. 5 mm grating period at 1.1 mm far-IR
        wavelength).  Two guards added: (1) inputs above 1 m are
        rejected as unambiguously wrong (``ValueError``); (2) an
        explicit ``_legacy_units`` kwarg (``'auto'`` / ``'um'`` /
        ``'SI'``) lets THz / MMW users bypass the heuristic.  Pass
        ``_legacy_units='SI'`` to opt out of the auto rescale and
        accept mm-scale inputs as SI metres.  Supported wavelength
        range: 10 nm (``1e-8 m``) -- 1 mm (``1e-3 m``) under the
        ``'auto'`` mode; up to 1 m under ``'SI'`` mode.

    .. versionchanged:: 5.30
        ``_legacy_units`` default flipped ``'auto'`` -> ``'SI'`` **and the
        micrometre auto-detect mode was removed entirely** (audit E-H11,
        ``AUDIT_ADVERSARIAL_CODEBASE_2026_07_25``, executed in the W5
        shim-removal wave).  The ``'auto'`` heuristic silently multiplied
        any ``periodx`` / ``periody`` / ``waveln`` above 1 mm by ``1e-6``,
        so a physically correct SI THz / MMW design (8 mm period at 1.1 mm
        wavelength) came back with 5e-10 m cells -- a factor 1e-6 wrong --
        and the only diagnostic was a ``DeprecationWarning``, which is
        suppressed by default outside ``__main__``.  SI metres are now
        taken at face value: no rescale, no warning.  A shim that
        SILENTLY REWRITES physical inputs cannot be left reachable once
        it is known wrong for a legitimate design regime, so ``'auto'``
        was retired rather than given another cycle: passing
        ``_legacy_units='auto'`` now raises ``ValueError`` naming the two
        surviving modes.  Explicit ``_legacy_units='um'`` is unchanged and
        is the supported migration path for genuine micrometre call
        sites: ``'auto'``'s per-parameter rescale is reproduced exactly by
        ``'um'`` whenever every parameter was micrometre-valued (its own
        documented use case), and a hybrid call must state which values
        are which rather than have a magnitude heuristic guess.

    Parameters
    ----------
    periodx : float
        Grating period in x [m].  Default ``61e-6`` (61 um).
    periody : float
        Grating period in y [m].  Default ``61e-6`` (61 um).
    waveln : float
        Design wavelength [m].  Default ``1.31e-6`` (1.31 um, telecom
        O-band).
    wavsamp : float
        Spatial sampling expressed in wavelengths (e.g. 0.5 -> half-wavelength).
    phaselevels : int
        Number of quantised phase levels in the final grating.
    phasesteps : int
        Annealing schedule exponent -- controls how quickly phase quantisation
        tightens over iterations.
    diforders : np.ndarray or None
        2-D array specifying the target diffraction-order pattern (amplitudes).
        ``None`` defaults to ``np.ones((12, 12))``.
    diffractionthr : float
        Intensity threshold used to identify "active" orders when computing
        uniformity and efficiency metrics.
    nfmov : float
        Near-field blending / momentum factor (0-1).  Smaller values make
        early iterations more conservative.
    itr : int
        Total number of IFTA iterations.
    plot : bool
        If True, display progress plots every *plot_every* iterations and at
        completion.
    plot_every : int
        Plotting cadence (iterations between plot updates).
    seed : int or None
        Random seed for reproducibility.  ``None`` leaves the RNG unseeded.
    save_path : str or None
        If provided, save the final quantized phase (radians) to this file
        in CSV format compatible with :func:`load_phase_file`.
    cell_pixels : int, (int, int), or None, default ``None``
        Force the unit-cell pixel count directly, overriding the
        ``wavsamp``-derived grid size.  ``None`` (default) keeps the
        historical behaviour: the cell is
        ``ndifordersx = ceil(periodx / (wavsamp * waveln) * 0.5) * 2``
        pixels wide (and similarly in y).  An ``int`` sets both axes to
        that many pixels; a ``(nx, ny)`` tuple sets them independently.

        The primary use is **grid-native DOE design**: choose
        ``cell_pixels = round(period / dx_grid)`` so the returned
        ``cell_pixel_size`` equals your propagation grid spacing
        ``dx_grid`` *exactly* and the cell tiles an integer number of
        grid pixels.  :func:`create_periodic_phase_mask` then maps one
        cell pixel to one grid pixel (no nearest-neighbour resample), so
        the phase transitions land on grid lines and no power is
        scattered out of the design orders by sampling jitter.  Each
        count must be even (the annealing / order-embedding logic uses
        ``n // 2``) and at least as large as the corresponding
        ``diforders`` dimension.
    _legacy_units : {'SI', 'um'}, default ``'SI'``
        Unit system of ``periodx`` / ``periody`` / ``waveln``.

        - ``'SI'`` (default since v5.30): the inputs are SI metres,
          unconditionally -- no rescale, no warning, even if values
          exceed 1 mm.  This is correct for THz / MMW designs where
          ``periodx=5e-3`` (5 mm) and ``waveln=1.1e-3`` (1.1 mm
          far-IR) are physically meaningful.
        - ``'um'``: the inputs are interpreted as legacy micrometres
          unconditionally -- each value is multiplied by ``1e-6``.
          No warning is emitted (the caller stated the convention).
          This is the supported migration path for call sites that
          still hold micrometre values.

        ``'auto'`` (the v4.14.2 per-parameter ">1 mm means micrometres"
        heuristic) was **removed in v5.30** and raises ``ValueError``.
        It was the default up to v5.29, where it silently miscompiled
        every SI THz / MMW design.

        In ``'SI'`` mode, inputs above 1 m are rejected as unambiguously
        wrong -- a metre-scale grating period or design wavelength is
        nonsense.  ``'um'`` mode has no upper bound on the raw input (the
        caller stated micrometres) and its rescaled result is not bounded
        either, matching the prior behaviour.

    Returns
    -------
    nearfield : np.ndarray (complex)
        Final near-field distribution (phase-only, quantized to phaselevels).
    farfield : np.ndarray (complex)
        Far-field (Fourier plane) distribution at the last iteration.
    cell_pixel_size : tuple of (float, float)
        Physical pixel spacing ``(dx, dy)`` of the near-field array [m].
        For square gratings (``periodx == periody``), both values are equal.

    Examples
    --------
    >>> # Default 12x12 spot array at 1.31 um -- SI metres throughout
    >>> nf, ff, cell_dx = makedammann2d(plot=False)
    >>>
    >>> # Custom 8x8 array, visible wavelength, fewer phase levels
    >>> nf, ff, cell_dx = makedammann2d(
    ...     periodx=80e-6, periody=80e-6, waveln=633e-9,
    ...     diforders=np.ones((8, 8)),
    ...     phaselevels=4, itr=1000, plot=False, seed=42,
    ... )

    Notes
    -----
    Ported to Python by Andrew Traverso from the original Octave/MATLAB
    implementation (makedammann2d.m) by Daniel Marks.
    """
    from numpy.fft import fft2, fftshift, ifft2, ifftshift

    # v4.14.3: dispatch on ``_legacy_units``.  Two modes (v5.30):
    #
    #   'SI'   -- pass-through, accept mm-scale inputs as SI metres
    #             (intended for THz / MMW designs).  DEFAULT since
    #             v5.30 (audit E-H11).
    #   'um'   -- explicit legacy micrometres; rescale unconditionally
    #             with NO warning.
    #
    # v5.30 (W5 shim-removal wave): the v4.14.2 ``'auto'`` heuristic is
    # REMOVED.  It rescaled by 1e-6 whenever a value exceeded 1 mm, which
    # is exactly wrong for a physical THz / MMW design; retiring it to an
    # explicit opt-in (v5.30 audit E-H11) was the first step, deleting it
    # the second.  A shim that silently rewrites physical inputs is not
    # given another cycle.  Precedent for the explicit named rejection:
    # ``propagators/system.py`` ``_reject_legacy`` (v5.0 aperture schema)
    # -- the mode name INTERCEPTED VALUES, so a bare "not valid" message
    # would leave a migrating caller without the recipe.
    if _legacy_units == 'auto':
        raise ValueError(
            "makedammann2d: _legacy_units='auto' was REMOVED in v5.30.  "
            "The v4.14.2 heuristic rescaled any periodx / periody / "
            "waveln above 1 mm by 1e-6, which silently miscompiled every "
            "physically-correct SI THz / MMW design (an 8 mm period at "
            "1.1 mm wavelength came back with 5e-10 m cells).  Migrate: "
            "pass SI metres and drop the kwarg entirely ('SI' is the "
            "default since v5.30), or pass _legacy_units='um' to convert "
            "micrometre-valued inputs explicitly (periodx=61.0, "
            "waveln=1.31 -> 61 um / 1.31 um).  Mixed-unit calls must be "
            "normalised by the caller -- no heuristic guesses which is "
            "which."
        )
    # Validate the mode here so a typo (e.g. ``_legacy_units='m'``)
    # fails fast rather than silently picking up a fallback.
    if _legacy_units not in ('um', 'SI'):
        raise ValueError(
            f"makedammann2d: _legacy_units={_legacy_units!r} is not "
            "valid; expected one of 'um', 'SI'."
        )

    # DOE-nit (AUDIT_DOE_GRATING_FREEFORM): validate the loop / sampling
    # counts.  ``itr < 1`` makes the annealing schedule
    # ``2**floor(phasesteps*(itr-it)/itr)`` a 0/0 -> ``int(nan)`` crash, and
    # ``wavsamp <= 0`` blows up ``ndifordersx = ceil(.../wavsamp)``.  Give an
    # actionable message instead of a deep-stack error.
    if int(itr) < 1:
        raise ValueError(
            f"makedammann2d: itr must be >= 1 (got {itr!r}); it sets the "
            "annealing iteration budget.")
    if not (wavsamp > 0):
        raise ValueError(
            f"makedammann2d: wavsamp must be > 0 (got {wavsamp!r}); it sets "
            "the wavelength/diffraction-order sampling density.")

    # v4.14.3 (P0-NEW-2 / Agent A A.2): unambiguous-nonsense upper
    # bound applies to ``'SI'`` mode.  A meter-scale grating period or
    # design wavelength is wrong under that interpretation.  Tests for
    # THz / MMW (mm-scale SI) designs depended on the ability to pass
    # ``periodx=5e-3``; the removed v4.14.2 ``'auto'`` heuristic
    # miscompiled those calls.  In ``'um'`` mode the caller explicitly
    # stated micrometres, so ``periodx=61.0`` (61 um) is a legitimate
    # value -- skip the upper bound there.
    def _reject_above_one_metre():
        if periodx > 1.0:
            raise ValueError(
                f"makedammann2d: periodx={periodx} m exceeds 1 m; "
                "if your input is in micrometres, the auto-detect form "
                "was REMOVED in v5.30 -- pass SI metres explicitly (e.g. "
                "``periodx=61e-6``) or set ``_legacy_units='um'``.  "
                "If your input is genuinely in metres, the value is "
                "physically implausible for a Dammann grating."
            )
        if periody > 1.0:
            raise ValueError(
                f"makedammann2d: periody={periody} m exceeds 1 m; "
                "if your input is in micrometres, the auto-detect form "
                "was REMOVED in v5.30 -- pass SI metres explicitly (e.g. "
                "``periody=61e-6``) or set ``_legacy_units='um'``.  "
                "If your input is genuinely in metres, the value is "
                "physically implausible for a Dammann grating."
            )
        if waveln > 1.0:
            raise ValueError(
                f"makedammann2d: waveln={waveln} m exceeds 1 m; "
                "if your input is in micrometres, the auto-detect form "
                "was REMOVED in v5.30 -- pass SI metres explicitly (e.g. "
                "``waveln=1.31e-6``) or set ``_legacy_units='um'``.  "
                "If your input is genuinely in metres, the value is "
                "physically implausible for a design wavelength."
            )

    if _legacy_units == 'um':
        # Explicit-legacy migration path.  Caller knows the inputs are
        # micrometres -- silent rescale with no warning.
        periodx = periodx * 1e-6
        periody = periody * 1e-6
        waveln = waveln * 1e-6
    else:
        # Explicit SI metres (the default).  Pass through unchanged --
        # this is the THz / MMW escape hatch.
        _reject_above_one_metre()

    if diforders is None:
        diforders = np.ones((12, 12))
    diforders = np.asarray(diforders, dtype=float)

    # 4.12.0 (B1-11): use a local Generator (np.random.default_rng)
    # instead of seeding the global ``np.random`` state.  Pre-4.12.0
    # the call ``np.random.seed(seed)`` perturbed the user's process-
    # wide RNG state -- a high-severity library anti-pattern, since
    # any other code in the same Python session that depended on
    # legacy ``np.random`` reproducibility silently lost it after a
    # ``makedammann2d`` call.  The local generator gives the same
    # bit-for-bit output for a given ``seed=`` while leaving the
    # global RNG untouched.
    rng = np.random.default_rng(seed)

    # -- Grid sizing -------------------------------------------------------
    ndifordersx = int(np.ceil(periodx / (wavsamp * waveln) * 0.5)) * 2
    ndifordersy = int(np.ceil(periody / (wavsamp * waveln) * 0.5)) * 2

    # Grid-native override: pin the cell pixel count directly so the
    # returned cell_pixel_size == the caller's propagation grid dx and the
    # cell tiles an integer number of grid pixels (lossless 1:1 mapping in
    # create_periodic_phase_mask).  See the ``cell_pixels`` docstring.
    if cell_pixels is not None:
        if np.isscalar(cell_pixels):
            _cpx = _cpy = int(cell_pixels)
        else:
            _cpx, _cpy = (int(v) for v in cell_pixels)
        for _lbl, _cp, _nord in (('x', _cpx, diforders.shape[0]),
                                 ('y', _cpy, diforders.shape[1])):
            if _cp < 2 or _cp % 2 != 0:
                raise ValueError(
                    f"makedammann2d: cell_pixels[{_lbl}]={_cp} must be an "
                    "even integer >= 2 (the annealing / order-embedding "
                    "logic indexes with n // 2).")
            if _cp < _nord:
                raise ValueError(
                    f"makedammann2d: cell_pixels[{_lbl}]={_cp} is smaller "
                    f"than the target order count ({_nord}); the cell cannot "
                    "hold the requested diffraction orders.")
        ndifordersx = _cpx
        ndifordersy = _cpy

    samplingx = periodx / ndifordersx
    samplingy = periody / ndifordersy

    # -- Target diffraction order pattern ----------------------------------
    # Symmetric centred placement: without this the port from the
    # Octave code's 1-based ``ceil((N - n) / 2) + 1`` fell into an
    # off-by-one when ``(N - n)`` was odd, placing the input pattern
    # one cell to the left of centre.  That broke the binary symmetry
    # Dammann designs depend on.  Plain integer division gives a
    # symmetric embedding in both parities.
    totaldiforders = np.zeros((ndifordersx, ndifordersy))
    x0 = (ndifordersx - diforders.shape[0]) // 2
    y0 = (ndifordersy - diforders.shape[1]) // 2
    totaldiforders[x0:x0 + diforders.shape[0], y0:y0 + diforders.shape[1]] = diforders

    # Axis vectors for plotting
    diforderx_ax = np.arange(-ndifordersx // 2, ndifordersx // 2)
    difordery_ax = np.arange(-ndifordersy // 2, ndifordersy // 2)
    rxscal = (np.arange(-ndifordersx // 2 + 0.5, ndifordersx // 2 - 0.5 + 1e-9)) * samplingx
    ryscal = (np.arange(-ndifordersy // 2 + 0.5, ndifordersy // 2 - 0.5 + 1e-9)) * samplingy

    # -- Initial near-field (separable random phase) -----------------------
    phsx, phsy = np.meshgrid(
        rng.random(ndifordersx),
        rng.random(ndifordersy),
        indexing='ij',
    )
    nearfield = np.exp(2j * np.pi * (phsx + phsy) - 1j * np.pi)

    # -- Iteration ---------------------------------------------------------
    totaldifnorm = (np.sum(np.abs(totaldiforders) ** 2) / totaldiforders.size) ** 0.5

    farfieldamp = None
    farfield = None

    if plot:
        import matplotlib.pyplot as plt
        plt.ion()
        fig, axes = plt.subplots(1, 3, figsize=(15, 4))

    nfmov_cur = nfmov

    for it in range(itr + 1):
        phaselevelscur = phaselevels * 2 ** int(np.floor(phasesteps * (itr - it) / itr))

        if it == itr:
            nfmov_cur = 0

        # Forward transform (near field -> far field)
        farfield = fftshift(fft2(fftshift(nearfield))) / np.sqrt(nearfield.size)

        # Amplitude replacement in the far field
        if it == 0:
            farfieldamp = totaldiforders.copy()
        else:
            farfieldamp = 0.00001 + (farfieldamp / np.abs(farfield)) * totaldiforders

        # Normalise far-field amplitude
        farfieldamp = farfieldamp * totaldifnorm / np.sqrt(
            np.sum(farfieldamp ** 2) / farfieldamp.size
        )

        # Combine amplitude constraint with current phase.
        #
        # Audit P2-07 (post-v5.17.0): this used ``np.sign(farfield)``,
        # which is only the Octave ``sign()`` (= z/|z|) this port needs
        # on NumPy >= 2.0.  On NumPy 1.x complex ``np.sign`` returned
        # ``sign(z.real)`` (falling back to ``sign(z.imag)`` on the
        # imaginary axis), so the far-field phase was replaced by +-1
        # each iteration and the IFTA silently degenerated (8x8
        # target, itr=200: uniformity 0.97 -> 0.00).
        #
        # v5.38: ``numpy>=2.0`` is now the packaged floor, so that
        # hazard is EXCLUDED rather than defended against.  The explicit
        # unit phasor stays because it is what the port means -- z/|z|,
        # 0-safe (0 -> 0, matching ``np.sign(0) == 0``) -- and it is
        # bit-identical to NumPy 2.x complex ``np.sign`` (A/B verified),
        # so nothing about the shipped answer depends on the choice.
        _ff_mag = np.hypot(farfield.real, farfield.imag)
        _ff_unit = np.zeros_like(farfield)
        np.divide(farfield.real, _ff_mag, out=_ff_unit.real,
                  where=_ff_mag > 0)
        np.divide(farfield.imag, _ff_mag, out=_ff_unit.imag,
                  where=_ff_mag > 0)
        farfield2 = farfieldamp * _ff_unit

        # Inverse transform (far field -> near field)
        nearfield2 = ifftshift(ifft2(ifftshift(farfield2))) * np.sqrt(farfield2.size)

        # Quantise phase
        phs = (
            np.floor(0.5 + np.angle(nearfield2) * (phaselevelscur / (2 * np.pi)))
            * (2 * np.pi / phaselevelscur)
        )

        # Blending / momentum update
        nfmovitr = nfmov_cur + (1.0 - nfmov_cur) * (it / itr)
        nearfield = (1 - nfmovitr) * nearfield + nfmovitr * (totaldifnorm * np.exp(1j * phs))

        # -- Plotting ------------------------------------------------------
        if plot and (it % plot_every == 0 or it == itr):
            for ax in axes:
                ax.clear()

            # v4.14.2: ``rxscal``/``ryscal`` are now in SI metres
            # (post-SI conversion); scale to micrometres for display
            # so the plot axes match the historical user expectation.
            _um = 1e6
            axes[0].imshow(
                np.angle(nearfield).T,
                extent=[rxscal[0] * _um, rxscal[-1] * _um,
                        ryscal[-1] * _um, ryscal[0] * _um],
                aspect='auto',
            )
            axes[0].set_title(f'Phase Levels {phaselevelscur}')
            axes[0].set_xlabel('Distance (um)')
            axes[0].set_ylabel('Distance (um)')

            axes[1].imshow(
                np.abs(nearfield).T,
                extent=[rxscal[0] * _um, rxscal[-1] * _um,
                        ryscal[-1] * _um, ryscal[0] * _um],
                aspect='auto',
            )
            axes[1].set_title('Absolute value')
            axes[1].set_xlabel('Distance (um)')
            axes[1].set_ylabel('Distance (um)')

            diffrac = np.abs(farfield) ** 2
            active = diffrac[diffrac > diffractionthr]
            if active.size > 0:
                ratiodif = active.min() / active.max()
                efficiencydif = active.sum() / diffrac.sum()
            else:
                ratiodif = 0.0
                efficiencydif = 0.0

            axes[2].imshow(
                diffrac.T,
                extent=[diforderx_ax[0], diforderx_ax[-1], difordery_ax[-1], difordery_ax[0]],
                aspect='auto',
            )
            axes[2].set_title(
                f'Diffractive power {ratiodif:.4g} ratio, {efficiencydif:.4g} efficiency'
            )
            axes[2].set_xlabel('Diffraction order')
            axes[2].set_ylabel('Diffraction order')

            fig.tight_layout()
            plt.pause(0.25)

    # Final quantization to target phase levels (not binary)
    final_phase = (
        np.floor(0.5 + np.angle(nearfield) * (phaselevels / (2 * np.pi)))
        * (2 * np.pi / phaselevels)
    )
    nearfield = np.exp(1j * final_phase)

    # Physical pixel size [m] -- v4.14.2 (P1-NEW-6): the internal math
    # now operates in SI metres end-to-end (``periodx``/``periody`` are
    # the SI inputs after the legacy-um normalisation above), so
    # ``samplingx`` already carries the metre unit and the legacy
    # ``* 1e-6`` um->m rescale is gone.
    cell_pixel_size_x = samplingx
    cell_pixel_size_y = samplingy
    cell_pixel_size = cell_pixel_size_x  # for square gratings; both returned below

    # Save to file if requested
    if save_path is not None:
        # ``cell_pixel_size`` is already in SI metres; ``save_phase_file``
        # handles the um conversion for human-readable header lines.
        # Metadata records the *period* and *wavelength* in micrometres
        # for backward-compatibility with older readers that expected
        # the ``_um`` suffix.
        save_phase_file(save_path, final_phase, cell_pixel_size=cell_pixel_size,
                        metadata={
                            'phaselevels': phaselevels,
                            'periodx_um': periodx * 1e6,
                            'periody_um': periody * 1e6,
                            'wavelength_um': waveln * 1e6,
                            'diforders': f'{diforders.shape[0]}x{diforders.shape[1]}',
                        })

    if plot:
        plt.ioff()
        plt.show()

    return nearfield, farfield, (cell_pixel_size_x, cell_pixel_size_y)


